export function lang() {
  return getSettings().language === 'fr' ? 'fr' : 'en';
}

/** Traduit une clé avec interpolation {variable}. */
export function t(key, vars = {}) {
  const str = messages[lang()][key] ?? messages.fr[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

/** Crée une erreur traduite, avec un code (la clé) et un statut HTTP optionnel. */
export function err(key, vars = {}, status) {
  return Object.assign(new Error(t(key, vars)), { code: key, ...(status ? { status } : {}) });
}
