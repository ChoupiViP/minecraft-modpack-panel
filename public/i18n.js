export const LANGS = { fr: 'Français', en: 'English' };
let current = 'en';

export function setLang(l) {
  current = messages[l] ? l : 'en';
  document.documentElement.lang = current;
}

export const getLang = () => current;
export const locale = () => (current === 'fr' ? 'fr-FR' : 'en-US');

/** Langue préférée du navigateur parmi celles disponibles. */
export function browserLang() {
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.slice(0, 2));
  return nav.find((l) => messages[l]) || 'en';
}

/** Traduit une clé ; {variables} remplacées telles quelles (à échapper par l'appelant si besoin). */
export function t(key, vars = {}) {
  const str = messages[current][key] ?? messages.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
